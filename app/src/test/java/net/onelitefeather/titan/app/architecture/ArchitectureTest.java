import net.minestom.server.event.EventNode;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

/**
 * Enforces the feature boundaries between {@code app.feature}, the platform and shared libraries.
 *
 * <p>{@link AnalyzeClasses} below excludes test sources ({@link ImportOption.DoNotIncludeTests}),
 * so these rules only check {@code app/src/main}; the test-only template feature under
 * {@code feature/example/} follows them only by convention.
 */
@AnalyzeClasses(packages = "net.onelitefeather.titan", importOptions = ImportOption.DoNotIncludeTests.class)
class ArchitectureTest {

    private static final String FEATURE_PACKAGE = "net.onelitefeather.titan.app.feature..";
    private static final String MODULE_PACKAGE = "net.onelitefeather.titan.app.module..";
    private static final String COMMON_PACKAGE = "net.onelitefeather.titan.common..";
    private static final String NAVIGATOR_PACKAGE = "net.onelitefeather.titan.app.feature.navigator..";
    private static final String AVAJE_CONFIG_PACKAGE = "io.avaje.config..";
    private static final String BOOTSTRAP_PACKAGE = "net.onelitefeather.titan.app.bootstrap..";

    /**
     * True for a class named {@code *Module}, or one Avaje Inject's annotation processor generated.
     */
    private static final DescribedPredicate<JavaClass> PUBLIC_FEATURE_API = DescribedPredicate.describe("named '*Module', or generated by Avaje Inject", javaClass -> isModuleType(javaClass) || isAvajeGeneratedType(javaClass));

    /** True for a call to the raw Minestom event API a feature must never reach for directly. */
    private static final DescribedPredicate<JavaMethodCall> TOUCHES_THE_RAW_EVENT_TREE = DescribedPredicate.describe("calls EventNode#addListener, EventNode#addChild or MinecraftServer#getGlobalEventHandler", ArchitectureTest::touchesTheRawEventTree);

    /**
     * True for a class in {@code app.feature..} that declares a method annotated with
     * {@link PostConstruct}.
     */
    private static final DescribedPredicate<JavaClass> DECLARES_POST_CONSTRUCT = DescribedPredicate.describe("declares a method annotated with @PostConstruct", javaClass -> javaClass.getMethods().stream().anyMatch(method -> method.isAnnotatedWith(PostConstruct.class)));

    /** Rule 1: a feature must never reach into another feature's package. */
    @ArchTest
    static final ArchRule featureModulesDoNotDependOnEachOther = slices().matching("net.onelitefeather.titan.app.feature.(*)..").should().notDependOnEachOther().because("a feature must never depend on another feature's package directly");

    /** Rule 2: the platform and shared libraries are what features depend on, never the reverse. */
    @ArchTest
    static final ArchRule platformAndCommonDoNotDependOnFeatures = noClasses().that().resideInAnyPackage(MODULE_PACKAGE, COMMON_PACKAGE).should().dependOnClassesThat().resideInAPackage(FEATURE_PACKAGE).because("the platform and shared libraries must stay usable without any particular feature present");

    /** Rule 3: a feature's only declared surface is its {@code *Module} entry point. */
    @ArchTest
    static final ArchRule onlyModuleTypesArePublicInFeatures = classes().that().resideInAPackage(FEATURE_PACKAGE).and().haveModifier(JavaModifier.PUBLIC).should(ArchConditions.be(PUBLIC_FEATURE_API)).because("only a feature's *Module entry point may be public");

    /**
     * Rule 4: a feature registers a listener only through
     * {@link net.onelitefeather.titan.app.module.FeatureNode}.
     */
    @ArchTest
    static final ArchRule featuresRegisterListenersOnlyThroughFeatureNode = noClasses().that().resideInAPackage(FEATURE_PACKAGE).should().callMethodWhere(TOUCHES_THE_RAW_EVENT_TREE).because("a feature must register listeners through FeatureNode, not the raw event API");

    /**
     * Rule 5: a class with an {@code @PostConstruct} method in {@code app.feature} must also be a
     * {@code @Singleton} bean.
     */
    @ArchTest
    static final ArchRule classesWithPostConstructInFeaturesAreSingleton = classes().that(DECLARES_POST_CONSTRUCT).should().beAnnotatedWith(Singleton.class).because("a class with an @PostConstruct method must also be a @Singleton bean, or Avaje Inject never discovers it");

    /**
     * Rule 6: a feature is built through constructor injection only, never via {@link BeanScope}.
     */
    @ArchTest
    static final ArchRule featureModulesDoNotUseBeanScope = noClasses().that().resideInAPackage(FEATURE_PACKAGE).should().dependOnClassesThat().areAssignableTo(BeanScope.class).because("a feature must get its dependencies through its constructor, never via BeanScope");

    /**
     * Rule 7: two features sharing an {@code EVENT_PRIORITY} value would make their event order
     * depend on an undocumented tie-break; checked via {@link ClassFileImporter} bytecode
     * inspection because ArchUnit has no built-in "unique field value" condition. Reading the
     * value from the field's {@code ConstantValue} attribute, rather than via reflection, avoids
     * initializing the declaring class - reflection would crash a feature whose static
     * initializer builds an {@code ItemStack} before a server exists.
     */
    @Test
    void eventPriorityValuesAreUniqueAcrossFeatures() {
        JavaClasses classes = new ClassFileImporter().withImportOption(new ImportOption.DoNotIncludeTests()).importPackages("net.onelitefeather.titan.app.feature");
        Map<Integer, List<String>> classNamesByPriority = new TreeMap<>();
        for (JavaClass javaClass : classes) {
            eventPriorityOf(javaClass).ifPresent(priority -> classNamesByPriority.computeIfAbsent(priority, unused -> new ArrayList<>()).add(javaClass.getSimpleName()));
        }
        List<String> duplicates = classNamesByPriority.entrySet().stream().filter(entry -> entry.getValue().size() > 1).map(entry -> entry.getKey() + ": " + entry.getValue()).toList();
        Assertions.assertTrue(duplicates.isEmpty(), "EVENT_PRIORITY values must be unique across every feature in app.feature, but found duplicates naming both: " + duplicates);
    }

    /**
     * @param javaClass a class found in {@code net.onelitefeather.titan.app.feature}
     * @return the {@code int} value of {@code javaClass}'s own {@code EVENT_PRIORITY} field, read
     *         from its class file's {@code ConstantValue} attribute, or empty if it declares none
     */
    private static OptionalInt eventPriorityOf(JavaClass javaClass) {
        String resourceName = javaClass.getName().replace('.', '/') + ".class";
        try (InputStream classBytes = ArchitectureTest.class.getClassLoader().getResourceAsStream(resourceName)) {
            if (classBytes == null) {
                return OptionalInt.empty();
            }
            ClassModel classModel = ClassFile.of().parse(classBytes.readAllBytes());
            for (FieldModel field : classModel.fields()) {
                if (!"EVENT_PRIORITY".equals(field.fieldName().stringValue())) {
                    continue;
                }
                for (Attribute<?> attribute : field.attributes()) {
                    if (attribute instanceof ConstantValueAttribute constantValue && constantValue.constant() instanceof IntegerEntry integerEntry) {
                        return OptionalInt.of(integerEntry.intValue());
                    }
                }
            }
            return OptionalInt.empty();
        } catch (IOException exception) {
            throw new UncheckedIOException("Unable to read the class file for " + javaClass.getName(), exception);
        }
    }

    /**
     * Rule 8: the navigator's destinations are fixed in code, not read from the
     * {@code io.avaje.config} facade.
     */
    @ArchTest
    static final ArchRule navigatorDoesNotDependOnAvajeConfig = noClasses().that().resideInAPackage(NAVIGATOR_PACKAGE).should().dependOnClassesThat().resideInAPackage(AVAJE_CONFIG_PACKAGE).because("the navigator's destinations are fixed in code, not read from configuration");

    /**
     * Rule 9: the platform ({@code app.module}) must not depend on the composition root
     * ({@code app.bootstrap}).
     */
    @ArchTest
    static final ArchRule platformDoesNotDependOnCompositionRoot = noClasses().that().resideInAPackage(MODULE_PACKAGE).should().dependOnClassesThat().resideInAPackage(BOOTSTRAP_PACKAGE).because("app.bootstrap depends on app.module types, never the reverse");

    ArchitectureTest() {
    }

    private static boolean touchesTheRawEventTree(JavaMethodCall call) {
        JavaClass owner = call.getTargetOwner();
        String methodName = call.getTarget().getName();
        boolean onEventNode = owner.isAssignableTo(EventNode.class) && ("addListener".equals(methodName) || "addChild".equals(methodName));
        boolean globalHandlerLookup = owner.isEquivalentTo(MinecraftServer.class) && "getGlobalEventHandler".equals(methodName);
        return onEventNode || globalHandlerLookup;
    }

    private static boolean isAvajeGeneratedType(JavaClass javaClass) {
        // getName() (full binary name), not getSimpleName(): ArchUnit treats "$" as a nested
        // class, so getSimpleName() on "FooModule$DI" returns just "DI" - too broad a match.
        return javaClass.getName().endsWith("$DI") && javaClass.isAnnotatedWith(Generated.class);
    }

    private static boolean isModuleType(JavaClass javaClass) {
        return javaClass.getSimpleName().endsWith("Module");
    }
}
